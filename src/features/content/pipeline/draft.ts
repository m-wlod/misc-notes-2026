import { parse } from "yaml";
import { z } from "zod";

/**
 * `pnpm content:draft <inbox-note>`: turns your raw notes into a brief for a Claude Code
 * writing session. It writes no lesson text itself (content is a separate task): it
 * checks the note, finds the lesson's place in the curriculum, and assembles everything
 * the writer needs, including the copyright rule and the exercise mix.
 */

const inboxSchema = z
  .object({
    /** The lesson id from content/curriculum.ts this note feeds. */
    lesson: z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/),
    sources: z
      .array(
        z.object({
          book: z.string().min(1),
          chapter: z.string().optional(),
          page: z.union([z.number(), z.string()]).optional(),
        }),
      )
      .min(1, "list the book(s) and chapter(s) these notes come from"),
  })
  .strict();

export type InboxNote = z.infer<typeof inboxSchema> & { notes: string };

export function parseInboxNote(raw: string): { note: InboxNote } | { errors: string[] } {
  const match = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(raw.replaceAll("\r\n", "\n"));
  if (!match)
    return { errors: ["front matter: start the note with --- lesson: <id> / sources: … ---"] };
  let data: unknown;
  try {
    data = parse(match[1] ?? "");
  } catch (e) {
    return {
      errors: [`front matter: ${e instanceof Error ? e.message.split("\n")[0] : "invalid YAML"}`],
    };
  }
  const parsed = inboxSchema.safeParse(data);
  if (!parsed.success) {
    return {
      errors: parsed.error.issues.map((i) => `${i.path.join(".") || "front matter"}: ${i.message}`),
    };
  }
  const notes = (match[2] ?? "").trim();
  if (notes.length < 40)
    return { errors: ["notes: the note body is empty or too short to draft from"] };
  return { note: { ...parsed.data, notes } };
}

export type LessonTarget = {
  id: string;
  title: string;
  level: number;
  prerequisites: string[];
  track: string;
  module: string;
  lessonFile: string;
  exercisesDir: string;
};

/** Exercise levels to aim for around the lesson's level, plus one interview-style item. */
export function exerciseMix(level: number): Record<number, number> {
  const mix: Record<number, number> = {};
  const add = (l: number, n: number) => {
    if (l >= 1 && l <= 5) mix[l] = (mix[l] ?? 0) + n;
  };
  add(level - 1, 3);
  add(level, 6);
  add(level + 1, 4);
  add(5, 1);
  return mix;
}

export function brief(
  note: InboxNote,
  target: LessonTarget,
  guide = "docs/CONTENT_GUIDE.md",
): string {
  const mix = Object.entries(exerciseMix(target.level))
    .map(([l, n]) => `level ${l}: ${String(n)}`)
    .join(", ");
  const sources = note.sources
    .map(
      (s) =>
        `- ${s.book}${s.chapter ? `, ch. ${s.chapter}` : ""}${s.page !== undefined ? `, p. ${String(s.page)}` : ""}`,
    )
    .join("\n");
  return `# Writing brief: ${target.title} (\`${target.id}\`)

Generated by \`pnpm content:draft\`. Paste this into a Claude Code session.

## Read first
- ${guide} (voice, templates, levels, review checklist). Follow it exactly.
- src/components/content/README.md (MDX components, math, numbering).

## Where it goes
- Track / module: ${target.track} / ${target.module}
- Lesson file (Polish, replace the \`<Stub />\` body; keep id, slug, prerequisites): \`${target.lessonFile}\`
- Exercises: \`${target.exercisesDir}/<exercise-id>.yaml\`
- Level: ${String(target.level)}. Prerequisites (assume the reader knows these): ${target.prerequisites.join(", ") || "none"}

## Copyright (non-negotiable)
The notes below are **sources, not text to copy**. Write in our own words; cite the book and
chapter in \`sources\`; quote at most one sentence, only when the exact wording matters.
Exercises must be original or substantially transformed, never lifted from the book.

## Deliverables
1. The lesson: \`status: draft\`, both depths (\`<Depth>\`) where the explanation differs,
   at least one \`<KeyFormula>\`, a \`<GuruMyth>\` if a common false claim exists, \`sources\`.
2. ${String(Object.values(exerciseMix(target.level)).reduce((a, b) => a + b, 0))} exercises (${mix}), all \`status: draft\`.
   Every numeric or symbolic exercise has a \`verify\` block; simulations set \`seed\`.
   Every exercise has at least one hint and a step-by-step solution.
3. Run \`pnpm content:build && pnpm content:verify && pnpm content:qa\` until they pass.

## Sources
${sources}

## Your notes
${note.notes}
`;
}
