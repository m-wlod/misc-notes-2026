import { ACHIEVEMENTS } from "./achievements";
import { TIERS } from "./config";
import en from "../../../messages/en/gamification.json";
import pl from "../../../messages/pl/gamification.json";

/**
 * The leagues and achievements catalog as SQL (Phase 14). `pnpm gamification:catalog`
 * writes it to the migration below; a unit test fails when code or messages change
 * without regenerating it. Upserts, so it's safe to apply over the local seed.
 */
/**
 * The latest catalog migration. A changed catalog gets a new file (applied migrations are
 * never edited); upserts make each file safe to run after the earlier ones.
 */
export const CATALOG_MIGRATION = "supabase/migrations/20261103120100_gamification_catalog.sql";

const q = (s: string) => `'${s.replaceAll("'", "''")}'`;

export function catalogSql(): string {
  const tiers = TIERS.map(
    (t) =>
      `  (${String(t.id)}, ${q(t.slug)}, ${q(pl.tiers[t.slug])}, ${q(en.tiers[t.slug])}, ${String(t.id)})`,
  );
  const achievements = ACHIEVEMENTS.map((a, i) => {
    const p = pl.achievements[a.id as keyof typeof pl.achievements];
    const e = en.achievements[a.id as keyof typeof en.achievements];
    return `  (${q(a.id)}, ${q(p.name)}, ${q(e.name)}, ${q(p.description)}, ${q(e.description)}, ${String((i + 1) * 10)})`;
  });
  return [
    "-- Leagues and achievements catalog (Phase 14). Generated by `pnpm gamification:catalog`",
    "-- from src/features/gamification and messages/*/gamification.json. Do not edit by hand.",
    "",
    "insert into public.leagues (id, slug, name_pl, name_en, tier) values",
    tiers.join(",\n"),
    "on conflict (id) do update set slug = excluded.slug, name_pl = excluded.name_pl,",
    "  name_en = excluded.name_en, tier = excluded.tier;",
    "",
    "insert into public.achievements (id, name_pl, name_en, description_pl, description_en, sort) values",
    achievements.join(",\n"),
    "on conflict (id) do update set name_pl = excluded.name_pl, name_en = excluded.name_en,",
    "  description_pl = excluded.description_pl, description_en = excluded.description_en,",
    "  sort = excluded.sort;",
    "",
  ].join("\n");
}
